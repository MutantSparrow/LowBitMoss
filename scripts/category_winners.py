"""Category winners from the evaluation files -> $LOWBITMOSS_HOME/eval/category_winners.md
Sources: eval/<tag>/metrics.json (CLIP/DINOv2/SSIM/PSNR/latent cos vs the teacher, from metrics.py), eval/hps3_summary.json (HPSv3 mu per prompt,
from hps3_score.py) and the judge scores in the JUDGE table below. CPU only, no model files.

  python -I scripts/category_winners.py
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _paths import EVAL

# Judge scores typed in by hand from the judge reports eval/judge_<tag>.md of the original work directory (those reports are not part of this
# repository). One Claude model instance opened the 24 images of a model and scored 0-5, so treat +-0.2 on an average as noise.
# (F faithfulness, T text, C counts/spatial, Q quality, A would-accept, text prompts acceptable /6, text prompts letter-exact /6, report file)
# None = not judged. To rank your own models, add rows from your own judge runs.
JUDGE = {
    "mixF_ptq":    (4.29, 4.36, 2.71, 4.29, 4.02, 5, None, "judge_mixF_ptq.md"),
    "mixG_x":      (4.50, 4.43, 3.36, 4.44, 4.29, 5, 4, "judge_mixG_x.md"),
    "mixG_tuned":  (4.48, 4.79, 3.64, 4.23, 4.21, 5, 6, "judge_mixG_tuned.md"),
    "mixH_tuned":  (4.31, 4.00, 3.29, 4.29, 4.10, 4, 3, "judge_mixH_tuned.md"),
    "mixH2_x":     (4.33, 4.00, 3.43, 4.27, 4.21, 4, 3, "judge_mixH2_x.md"),
    "mixH2_tuned": (4.29, 3.93, 3.36, 4.29, 4.17, 4, 2, "judge_mixH2_tuned.md"),
    "mixH2_xm_f8": (4.25, 4.00, 3.79, 4.21, 4.15, 5, 4, "judge_mixH2_xm_f8.md"),
    "mixI_tuned":  (3.54, 1.14, 2.07, 3.54, 3.15, 0, 0, "judge_mixI_tuned.md"),
}
# not judged separately: same model as another within fp8 rounding of the LoRA factors
SAME_AS = {"mixH2_x_f8": "mixH2_x"}
TAGS = ["mixF_ptq", "mixG_x", "mixG_tuned", "mixH_x", "mixH_tuned", "mixH2_x", "mixH2_x_f8", "mixH2_tuned", "mixH2_xm", "mixH2_xm_f8", "mixI_x", "mixI_tuned"]

hps = json.load(open(os.path.join(EVAL, "hps3_summary.json")))
teacher_mu = hps["teacher_bf16"]["mu_by_prompt"]
rows = {}
for t in TAGS:
    m = json.load(open(os.path.join(EVAL, t, "metrics.json")))["mean"]
    h = hps[t]
    mu = h["mu_by_prompt"]
    keys = list(mu.keys()) if isinstance(mu, dict) else list(range(len(mu)))
    d = [mu[k] - teacher_mu[k] for k in keys]
    dm = sum(d) / len(d)
    se = math.sqrt(sum((x - dm) ** 2 for x in d) / (len(d) - 1) / len(d))
    j = JUDGE.get(t) or JUDGE.get(SAME_AS.get(t, ""))
    rows[t] = dict(gb=h["size_gb"], clip=m["clip_student"], dino=m["dino_cos"], ssim=m["ssim"], psnr=m["psnr"], lat=m["latent_cos"],
                   hps=h["mean_mu"], hps_d=dm, hps_se=se, judge=j, judged=(t in JUDGE))

out = []
out.append("# Category winners\n")
out.append("Generated by scripts/category_winners.py from eval/*/metrics.json, eval/hps3_summary.json and the judge reports. 24 prompts, 768 px, one seed each; the judge is a Claude model\n"
           "instance (+-0.2 noise per average); HPSv3 paired SE vs the teacher is ~0.2-0.3 (differences below ~0.5 mu are not distinguishable).\n")
out.append("| tag | GB | judge accept A | judge text T | text exact /6 | HPSv3 mu (diff to teacher +- SE) | DINOv2 | SSIM | latent cos | CLIP |")
out.append("|---|---|---|---|---|---|---|---|---|---|")
for t in sorted(TAGS, key=lambda t: rows[t]["gb"]):
    r = rows[t]
    j = r["judge"]
    ja = ("%.2f" % j[4]) + ("" if r["judged"] else " (=%s)" % SAME_AS.get(t, "?")) if j else "-"
    jt = "%.2f" % j[1] if j else "-"
    je = "-" if (not j or j[6] is None) else str(j[6])
    out.append("| %s | %.2f | %s | %s | %s | %.2f (%+.2f +- %.2f) | %.3f | %.3f | %.3f | %.2f |" % (t, r["gb"], ja, jt, je, r["hps"], r["hps_d"], r["hps_se"], r["dino"], r["ssim"], r["lat"], r["clip"]))
out.append("")
w_over = max(JUDGE, key=lambda t: JUDGE[t][4])
ties = [t for t in JUDGE if JUDGE[t][4] >= JUDGE[w_over][4] - 0.2]
w_text = max(JUDGE, key=lambda t: JUDGE[t][1])
w_aes = max(TAGS, key=lambda t: rows[t]["hps"])
aes_group = [t for t in TAGS if rows[t]["hps"] >= rows[w_aes]["hps"] - 0.5]
w_close = max(TAGS, key=lambda t: rows[t]["dino"])
acceptable = [t for t in TAGS if rows[t]["judge"] is not None and rows[t]["judge"][4] >= 4.0]
w_size = min(acceptable, key=lambda t: rows[t]["gb"])
value = [t for t in acceptable if rows[t]["hps_d"] >= -0.5]
w_value = min(value, key=lambda t: rows[t]["gb"])
out.append("## Winners\n")
out.append("| category | winner | evidence | statistically tied with |")
out.append("|---|---|---|---|")
out.append("| best overall (judge 'would accept') | %s (A %.2f) | judge reports | %s |" % (w_over, JUDGE[w_over][4], ", ".join(t for t in ties if t != w_over)))
out.append("| best text rendering | %s (T %.2f, %s/6 letter-exact) | judge reports | none (next best T %.2f) |" % (w_text, JUDGE[w_text][1], JUDGE[w_text][6], sorted([JUDGE[t][1] for t in JUDGE])[-2]))
out.append("| best aesthetics (HPSv3) | %s (mu %.2f, teacher %.2f) | eval/hps3_summary.md | %s |" % (w_aes, rows[w_aes]["hps"], hps["teacher_bf16"]["mean_mu"], ", ".join(t for t in aes_group if t != w_aes)))
out.append("| closest to the teacher | %s (DINOv2 %.3f, SSIM %.3f, latent cos %.3f) | eval/*/metrics.json | none by DINOv2 (next %.3f) |" % (
    w_close, rows[w_close]["dino"], rows[w_close]["ssim"], rows[w_close]["lat"], sorted([rows[t]["dino"] for t in TAGS])[-2]))
out.append("| smallest acceptable (judge A >= 4.0) | %s (%.2f GB, A %.2f, HPSv3 %+.2f vs teacher) | judge + size | - |" % (w_size, rows[w_size]["gb"], JUDGE[w_size][4], rows[w_size]["hps_d"]))
out.append("| best size/quality value (A >= 4.0 and HPSv3 within 0.5 of the teacher) | %s (%.2f GB, HPSv3 %+.2f) | judge + HPSv3 + size | - |" % (w_value, rows[w_value]["gb"], rows[w_value]["hps_d"]))
out.append("")
out.append("Notes: mixH2_x_f8 was not judged separately (metrics identical to mixH2_x; same model within fp8 rounding of the LoRA factors). HPSv3 sees the int4 modulation layers (mixH2_xm*) as a real\n"
           "aesthetic cost (%+.2f vs %+.2f for fp8-LoRA only), which agrees with the judge's observation of a small cool/low-contrast drift. 1-bit-attention (mixI) and ternary/binary (tern_v1) are not acceptable.\n"
           % (rows["mixH2_xm_f8"]["hps_d"], rows["mixH2_x_f8"]["hps_d"]))
open(os.path.join(EVAL, "category_winners.md"), "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))
